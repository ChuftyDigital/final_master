#!/usr/bin/env python3
"""
LoRA Training Dataset Preparation for AI Influencer Pipeline
=============================================================

Prepares training datasets for kohya_ss LoRA training from master images:
  - Organises master images into the correct directory structure
  - Generates caption (.txt) files from character persona data
  - Creates the kohya_ss training configuration TOML
  - Sets up regularisation image directories
  - Supports batch preparation for all 21 characters

Expects master images to have been generated by Phase 1 of the orchestrator.

Usage:
    python prepare_lora_training.py --character aria_nova
    python prepare_lora_training.py --all
    python prepare_lora_training.py --character aria_nova --master-dir output/master_images/aria_nova

Dependencies:
    - characters/personas.json character database
    - config/lora_training_config.json training configuration
    - Pillow for image validation
"""

