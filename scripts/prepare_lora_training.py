def generate_training_toml(
    character: Dict,
    lora_config: Dict,
    dataset_dir: Path,
    output_dir: Path,
    reg_dir: Optional[Path] = None,
) -> str:
    """
    Generate a kohya_ss training configuration TOML file content.

    Parameters
    ----------
    character : dict
        Character persona data.
    lora_config : dict
        LoRA training configuration.
    dataset_dir : Path
        Path to the prepared training image directory.
    output_dir : Path
        Path where the trained LoRA will be saved.
    reg_dir : Path or None
        Path to regularisation images (if enabled).

    Returns
    -------
    str
        TOML-formatted configuration string.
    """
    training = lora_config.get("training", {})
    dataset = lora_config.get("dataset", {})
    model_cfg = lora_config.get("model", {})
    output_cfg = lora_config.get("output", {})
    reg_cfg = lora_config.get("regularization", {})

    slug = character.get("slug", character.get("id", "character"))
    trigger_word = character.get("trigger_word", slug)
    num_repeats = dataset.get("num_repeats", 50)

    # The image directory name follows kohya_ss convention: {num_repeats}_{trigger_word}
    img_folder_name = f"{num_repeats}_{trigger_word}"

    # Build TOML structure
    output_name = output_cfg.get("output_name_template", "{character_slug}_lora_v1").format(
        character_slug=slug
    )

    # Manual TOML building (avoids strict toml library dependency)
    lines = [
        "[general]",
        f'enable_bucket = {str(dataset.get("enable_bucket", True)).lower()}',
        f'shuffle_caption = {str(dataset.get("shuffle_caption", True)).lower()}',
        f'caption_extension = "{lora_config.get("caption", {}).get("extension", ".txt")}"',
        f'keep_tokens = {dataset.get("keep_tokens", 1)}',
        "",
        "[[datasets]]",
        f'resolution = {dataset.get("resolution", 1024)}',
        f'batch_size = {training.get("train_batch_size", 2)}',
        f'min_bucket_reso = {dataset.get("min_bucket_reso", 512)}',
        f'max_bucket_reso = {dataset.get("max_bucket_reso", 2048)}',
        f'bucket_reso_steps = {dataset.get("bucket_reso_steps", 64)}',
        f'bucket_no_upscale = {str(dataset.get("bucket_no_upscale", True)).lower() if "bucket_no_upscale" in dataset else str(training.get("bucket_no_upscale", True)).lower()}',
        "",
        "  [[datasets.subsets]]",
        f'  image_dir = "{dataset_dir / img_folder_name}"',
        f'  num_repeats = {num_repeats}',
        f'  class_tokens = "{trigger_word}"',
        f'  flip_aug = {str(dataset.get("flip_aug", False)).lower()}',
        f'  color_aug = {str(dataset.get("color_aug", False)).lower()}',
        f'  random_crop = {str(dataset.get("random_crop", False)).lower()}',
    ]

    # Add regularisation subset if enabled
    if reg_cfg.get("enabled", False) and reg_dir and reg_dir.exists():
        reg_repeats = reg_cfg.get("num_repeats", 1)
        class_prompt = reg_cfg.get("class_prompt", "a person")
        reg_folder_name = f"{reg_repeats}_{class_prompt.replace(' ', '_')}"
        lines.extend([
            "",
            "  [[datasets.subsets]]",
            f'  image_dir = "{reg_dir / reg_folder_name}"',
            f'  num_repeats = {reg_repeats}',
            f'  class_tokens = "{class_prompt}"',
            '  is_reg = true',
        ])

    model_type = model_cfg.get("model_type", "flux")
    is_flux = model_type == "flux"

    lines.extend([
        "",
        "[training_arguments]",
        f'pretrained_model_name_or_path = "{model_cfg.get("pretrained_model", "models/unet/z_image_bf16.safetensors")}"',
        f'output_dir = "{output_dir}"',
        f'output_name = "{output_name}"',
        f'save_model_as = "{training.get("save_model_as", "safetensors")}"',
        f'max_train_steps = {training.get("max_train_steps", 1500)}',
        f'save_every_n_steps = {training.get("save_every_n_steps", 500)}',
        f'learning_rate = {training.get("learning_rate", 5e-5)}',
        f'unet_lr = {training.get("unet_lr", 5e-5)}',
        f'text_encoder_lr = {training.get("text_encoder_lr", 1e-5)}',
        f'optimizer_type = "{training.get("optimizer_type", "prodigy")}"',
        f'lr_scheduler = "{training.get("lr_scheduler", "cosine_with_restarts")}"',
        f'lr_warmup_steps = {training.get("lr_warmup_steps", 100)}',
        f'lr_scheduler_num_cycles = {training.get("lr_scheduler_num_cycles", 3)}',
        f'network_dim = {training.get("network_dim", 16)}',
        f'network_alpha = {training.get("network_alpha", 8)}',
        f'mixed_precision = "{training.get("mixed_precision", "bf16")}"',
        f'full_bf16 = {str(training.get("full_bf16", True)).lower()}',
        f'gradient_checkpointing = {str(training.get("gradient_checkpointing", True)).lower()}',
        f'gradient_accumulation_steps = {training.get("gradient_accumulation_steps", 1)}',
        f'max_token_length = {training.get("max_token_length", 512)}',
        f'seed = {training.get("seed", 42)}',
        f'cache_latents = {str(training.get("cache_latents", True)).lower()}',
        f'cache_latents_to_disk = {str(training.get("cache_latents_to_disk", False)).lower()}',
        f'cache_text_encoder_outputs = {str(training.get("cache_text_encoder_outputs", True)).lower()}',
        f'noise_offset = {training.get("noise_offset", 0.0357)}',
        f'adaptive_noise_scale = {training.get("adaptive_noise_scale", 0.00357)}',
        f'min_snr_gamma = {training.get("min_snr_gamma", 5)}',
    ])

    # Flux uses SDPA, SDXL uses xformers
    if is_flux:
        if training.get("sdpa", True):
            lines.append(f'sdpa = true')
    else:
        lines.append(f'xformers = {str(training.get("xformers", True)).lower()}')
        lines.append(f'clip_skip = {training.get("clip_skip", 2)}')

    # Optimizer arguments
    opt_args = training.get("optimizer_args", {})
    if opt_args:
        opt_parts = []
        for k, v in opt_args.items():
            if isinstance(v, bool):
                opt_parts.append(f"{k}={str(v).lower()}")
            elif isinstance(v, str):
                opt_parts.append(f'{k}="{v}"')
            else:
                opt_parts.append(f"{k}={v}")
        lines.append(f'optimizer_args = [{", ".join(repr(p) for p in opt_parts)}]')

    # VAE and CLIP paths
    vae_path = model_cfg.get("vae", "")
    if vae_path:
        lines.append(f'vae = "{vae_path}"')
    clip_path = model_cfg.get("clip", "")
    if clip_path:
        lines.append(f'clip_l = "{clip_path}"')

    # Sample generation during training
    sample_steps = output_cfg.get("sample_every_n_steps", 500)
    sample_prompts = output_cfg.get("sample_prompts_file", "")
    if sample_prompts:
        lines.append(f'sample_every_n_steps = {sample_steps}')
        lines.append(f'sample_prompts = "{sample_prompts}"')
        lines.append(f'sample_sampler = "{output_cfg.get("sample_sampler", "sa_solver")}"')

    # Logging
    log_dir = output_cfg.get("log_dir", "output/logs/lora_training")
    lines.append(f'logging_dir = "{log_dir}"')
    lines.append(f'log_prefix = "{slug}_"')

    return "\n".join(lines) + "\n"


