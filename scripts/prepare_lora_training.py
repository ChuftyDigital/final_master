def load_json(path: Path) -> Dict:
    """Load a JSON file and return its contents."""
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def load_personas(path: Path = PERSONAS_PATH) -> Dict:
    """Load the character personas database."""
    return load_json(path)


def load_lora_config(path: Path = LORA_CONFIG_PATH) -> Dict:
    """Load the LoRA training configuration."""
    return load_json(path)


def get_character_slugs(personas: Dict) -> List[str]:
    """Return sorted list of all character slugs."""
    characters = personas.get("characters", personas)
    if isinstance(characters, list):
        return sorted([c.get("slug", c.get("id", "")) for c in characters])
    if isinstance(characters, dict):
        return sorted(characters.keys())
    return []


def get_character(personas: Dict, slug: str) -> Dict:
    """Retrieve a single character's data by slug."""
    characters = personas.get("characters", personas)
    if isinstance(characters, list):
        for c in characters:
            if c.get("slug") == slug or c.get("id") == slug:
                return c
        raise KeyError(f"Character '{slug}' not found")
    if isinstance(characters, dict):
        if slug in characters:
            return characters[slug]
        raise KeyError(f"Character '{slug}' not found")
    raise ValueError("Unexpected personas format")


def find_images(directory: Path) -> List[Path]:
    """Find all image files in a directory (non-recursive)."""
    if not directory.exists():
        return []
    images = []
    for f in sorted(directory.iterdir()):
        if f.is_file() and f.suffix.lower() in IMAGE_EXTENSIONS:
            images.append(f)
    return images


def validate_image(path: Path, min_size: int = 512) -> bool:
    """
    Validate that an image file is readable and meets minimum size requirements.

    Returns True if the image is valid, False otherwise.
    """
    if Image is None:
        # Pillow not available; skip validation
        return path.exists() and path.stat().st_size > 0

    try:
        with Image.open(path) as img:
            w, h = img.size
            if w < min_size or h < min_size:
                logger.warning(
                    "Image %s is too small (%dx%d, minimum %d). Consider regenerating.",
                    path.name, w, h, min_size
                )
                return False
            return True
    except Exception as exc:
        logger.error("Cannot read image %s: %s", path, exc)
        return False


