def generate_caption(
    character: Dict,
    lora_config: Dict,
    image_index: int = 0,
) -> str:
    """
    Generate a caption string for a training image based on persona data.

    The caption follows the template from lora_training_config.json and includes
    the trigger word, character attributes, and style tags.

    Parameters
    ----------
    character : dict
        Character persona data.
    lora_config : dict
        LoRA training configuration (contains caption template settings).
    image_index : int
        Index of the image (for potential variation in captions).

    Returns
    -------
    str
        The caption string.
    """
    caption_cfg = lora_config.get("caption", {})
    template = caption_cfg.get(
        "template",
        "{trigger_word}, {ethnicity} {gender}, {hair_description}, "
        "{eye_color} eyes, {distinguishing_features}, {style_tags}"
    )
    separator = caption_cfg.get("tag_separator", ", ")
    max_tags = caption_cfg.get("max_tags", 30)

    # Extract character attributes with safe defaults
    slug = character.get("slug", character.get("id", "character"))
    trigger_word = character.get("trigger_word", slug)

    # Physical attributes
    physical = character.get("physical", character.get("appearance", {}))
    ethnicity = physical.get("ethnicity", character.get("ethnicity", ""))
    gender = physical.get("gender", character.get("gender", "woman"))
    hair_description = physical.get("hair", character.get("hair", ""))
    eye_color = physical.get("eye_color", character.get("eye_color", ""))
    distinguishing_features = physical.get(
        "distinguishing_features",
        character.get("distinguishing_features", "")
    )

    # Handle list-type features
    if isinstance(distinguishing_features, list):
        distinguishing_features = separator.join(distinguishing_features)
    if isinstance(hair_description, dict):
        hair_parts = []
        if "color" in hair_description:
            hair_parts.append(hair_description["color"])
        if "style" in hair_description:
            hair_parts.append(hair_description["style"])
        if "length" in hair_description:
            hair_parts.append(hair_description["length"])
        hair_description = " ".join(hair_parts)

    # Style tags
    style_tags_raw = character.get("style_tags", character.get("tags", []))
    if isinstance(style_tags_raw, list):
        style_tags = separator.join(style_tags_raw[:max_tags])
    else:
        style_tags = str(style_tags_raw)

    # Build caption from template
    caption = template.format(
        trigger_word=trigger_word,
        ethnicity=ethnicity,
        gender=gender,
        hair_description=hair_description,
        eye_color=eye_color,
        distinguishing_features=distinguishing_features,
        style_tags=style_tags,
    )

    # Clean up: remove double commas, extra spaces
    while ",," in caption:
        caption = caption.replace(",,", ",")
    while "  " in caption:
        caption = caption.replace("  ", " ")
    caption = caption.strip().strip(",").strip()

    # Enforce max tag count
    tags = [t.strip() for t in caption.split(",") if t.strip()]
    if len(tags) > max_tags:
        tags = tags[:max_tags]
    caption = separator.join(tags)

    return caption


