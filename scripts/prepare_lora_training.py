def prepare_dataset_for_character(
    character: Dict,
    lora_config: Dict,
    master_dir: Path,
    output_dir: Path,
    reg_dir: Optional[Path] = None,
) -> Path:
    """
    Prepare a complete LoRA training dataset for a single character.

    Steps:
      1. Validate and copy master images into kohya_ss directory structure
      2. Generate caption files for each image
      3. Create the training configuration TOML
      4. Set up regularisation images (if enabled)

    Parameters
    ----------
    character : dict
        Character persona data.
    lora_config : dict
        LoRA training configuration.
    master_dir : Path
        Directory containing the character's master images.
    output_dir : Path
        Destination directory for the prepared dataset.
    reg_dir : Path or None
        Source directory for regularisation images.

    Returns
    -------
    Path
        Path to the generated training TOML config file.
    """
    slug = character.get("slug", character.get("id", "character"))
    trigger_word = character.get("trigger_word", slug)
    dataset_cfg = lora_config.get("dataset", {})
    num_repeats = dataset_cfg.get("num_repeats", 50)

    logger.info("Preparing dataset for character: %s", slug)

    # -- Step 1: Validate master images --
    source_images = find_images(master_dir)
    expected_count = dataset_cfg.get("images_per_character", 3)

    if len(source_images) == 0:
        raise FileNotFoundError(
            f"No images found in {master_dir}. "
            f"Run 'orchestrator.py generate-masters --character {slug}' first."
        )

    if len(source_images) < expected_count:
        logger.warning(
            "Found %d images for %s, expected %d. Proceeding with available images.",
            len(source_images), slug, expected_count
        )

    # Validate images
    valid_images = []
    for img_path in source_images:
        if validate_image(img_path, min_size=dataset_cfg.get("resolution", 1024) // 2):
            valid_images.append(img_path)
        else:
            logger.warning("Skipping invalid image: %s", img_path)

    if not valid_images:
        raise ValueError(f"No valid images found for character {slug}")

    logger.info("  Found %d valid master images", len(valid_images))

    # -- Step 2: Create dataset directory structure --
    # kohya_ss expects: dataset_dir/{num_repeats}_{trigger_word}/image.png
    img_folder_name = f"{num_repeats}_{trigger_word}"
    img_dest_dir = output_dir / img_folder_name
    img_dest_dir.mkdir(parents=True, exist_ok=True)

    # Copy images with standardised names
    for idx, src_img in enumerate(valid_images):
        ext = src_img.suffix.lower()
        dest_name = f"{slug}_{idx:03d}{ext}"
        dest_path = img_dest_dir / dest_name
        shutil.copy2(src_img, dest_path)
        logger.info("  Copied: %s -> %s", src_img.name, dest_name)

    # -- Step 3: Generate caption files --
    caption_ext = lora_config.get("caption", {}).get("extension", ".txt")

    for idx in range(len(valid_images)):
        ext = valid_images[idx].suffix.lower()
        img_name = f"{slug}_{idx:03d}{ext}"
        caption_name = f"{slug}_{idx:03d}{caption_ext}"
        caption_path = img_dest_dir / caption_name

        caption_text = generate_caption(character, lora_config, image_index=idx)
        caption_path.write_text(caption_text, encoding="utf-8")
        logger.info("  Caption: %s -> %s", img_name, caption_name)

    # -- Step 4: Set up regularisation images --
    reg_cfg = lora_config.get("regularization", {})
    reg_dest_dir = None

    if reg_cfg.get("enabled", False):
        class_prompt = reg_cfg.get("class_prompt", "a person")
        reg_repeats = reg_cfg.get("num_repeats", 1)
        reg_folder_name = f"{reg_repeats}_{class_prompt.replace(' ', '_')}"
        reg_dest_dir = output_dir / reg_folder_name

        if reg_dir and reg_dir.exists():
            reg_dest_dir.mkdir(parents=True, exist_ok=True)
            reg_images = find_images(reg_dir)

            if reg_images:
                for idx, src_img in enumerate(reg_images):
                    ext = src_img.suffix.lower()
                    dest_path = reg_dest_dir / f"reg_{idx:04d}{ext}"
                    shutil.copy2(src_img, dest_path)

                logger.info(
                    "  Regularisation: copied %d images to %s",
                    len(reg_images), reg_dest_dir
                )
            else:
                logger.warning(
                    "  Regularisation enabled but no images found in %s", reg_dir
                )
                logger.warning(
                    "  Add generic person images to %s for better training results",
                    reg_dir,
                )
        else:
            reg_dest_dir.mkdir(parents=True, exist_ok=True)
            logger.warning(
                "  Regularisation enabled but source dir %s not found. "
                "Created empty directory: %s",
                reg_dir, reg_dest_dir,
            )
            logger.warning(
                "  Add 10-20 generic person images to %s before training",
                reg_dest_dir,
            )

    # -- Step 5: Generate training TOML --
    lora_output_dir = LORA_MODELS_DIR
    lora_output_dir.mkdir(parents=True, exist_ok=True)

    toml_content = generate_training_toml(
        character=character,
        lora_config=lora_config,
        dataset_dir=output_dir,
        output_dir=lora_output_dir,
        reg_dir=output_dir if reg_dest_dir else None,
    )

    toml_path = output_dir / f"{slug}_training_config.toml"
    toml_path.write_text(toml_content, encoding="utf-8")
    logger.info("  Training config: %s", toml_path)

    # -- Step 6: Create a sample prompts file for training preview --
    sample_prompts_path = output_dir / f"{slug}_sample_prompts.txt"
    sample_lines = [
        f"{trigger_word}, portrait photo, studio lighting, high quality --n low quality, blurry",
        f"{trigger_word}, full body photo, natural lighting, urban background --n low quality, distorted",
        f"{trigger_word}, close-up portrait, soft lighting, neutral background --n blurry, watermark",
    ]
    sample_prompts_path.write_text("\n".join(sample_lines) + "\n", encoding="utf-8")
    logger.info("  Sample prompts: %s", sample_prompts_path)

    # -- Summary --
    logger.info("  Dataset preparation complete for %s:", slug)
    logger.info("    Images: %d (in %s)", len(valid_images), img_dest_dir)
    logger.info("    Captions: %d .txt files", len(valid_images))
    logger.info("    Config: %s", toml_path)
    logger.info(
        "    Output LoRA will be: %s/%s_lora_v1.safetensors",
        lora_output_dir, slug,
    )

    return toml_path


def prepare_all_characters(
    personas: Dict,
    lora_config: Dict,
    master_base_dir: Path = MASTER_IMAGES_DIR,
    output_base_dir: Path = LORA_DATASETS_DIR,
    reg_dir: Optional[Path] = REG_IMAGES_DIR,
) -> List[Path]:
    """
    Prepare LoRA training datasets for all characters.

    Returns a list of paths to the generated TOML config files.
    """
    slugs = get_character_slugs(personas)
    logger.info("Preparing datasets for %d characters...", len(slugs))

    toml_paths = []
    errors = []

    for slug in slugs:
        try:
            character = get_character(personas, slug)
            master_dir = master_base_dir / slug
            output_dir = output_base_dir / slug

            toml_path = prepare_dataset_for_character(
                character=character,
                lora_config=lora_config,
                master_dir=master_dir,
                output_dir=output_dir,
                reg_dir=reg_dir,
            )
            toml_paths.append(toml_path)
        except Exception as exc:
            logger.error("Failed to prepare dataset for %s: %s", slug, exc)
            errors.append((slug, str(exc)))

    logger.info("")
    logger.info("=" * 60)
    logger.info("Batch preparation complete:")
    logger.info("  Successful: %d / %d", len(toml_paths), len(slugs))
    if errors:
        logger.warning("  Failed: %d", len(errors))
        for slug, err in errors:
            logger.warning("    - %s: %s", slug, err)
    logger.info("=" * 60)

    # Generate a batch training script
    if toml_paths:
        batch_script = generate_batch_training_script(toml_paths, output_base_dir, lora_config)
        logger.info("Batch training script: %s", batch_script)

    return toml_paths


def generate_batch_training_script(
    toml_paths: List[Path],
    output_dir: Path,
    lora_config: Optional[Dict[str, Any]] = None,
) -> Path:
    """
    Generate a bash script that trains all LoRAs sequentially.

    Parameters
    ----------
    toml_paths : list of Path
        Paths to the TOML training configs.
    output_dir : Path
        Directory to write the batch script.
    lora_config : dict, optional
        LoRA training config (used to determine model type).

    Returns
    -------
    Path
        Path to the generated batch training script.
    """
    # Determine training script based on model type
    model_type = "flux"
    if lora_config:
        model_type = lora_config.get("model", {}).get("model_type", "flux")
    train_script = "flux_train_network.py" if model_type == "flux" else "sdxl_train_network.py"

    script_path = output_dir / "train_all_loras.sh"
    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated batch LoRA training script",
        "# Run this after verifying datasets are correct",
        "#",
        "# Usage: bash train_all_loras.sh",
        "#",
        "# Requires: kohya_ss sd-scripts installed and accessible",
        f"# Model type: {model_type} (Z-Image Base / Flux architecture)",
        "# Optimised for RTX 5090 (32GB VRAM, bf16)",
        "",
        'set -euo pipefail',
        "",
        'KOHYA_DIR="${KOHYA_DIR:-/path/to/kohya_ss/sd-scripts}"',
        'ACCELERATE_CMD="accelerate launch"',
        "",
        'echo "Starting batch LoRA training..."',
        'echo "Using kohya_ss at: ${KOHYA_DIR}"',
        'echo ""',
        "",
    ]

    for idx, toml_path in enumerate(toml_paths, 1):
        name = toml_path.stem.replace("_training_config", "")
        lines.extend([
            f'echo "=== Training {idx}/{len(toml_paths)}: {name} ==="',
            f'${{ACCELERATE_CMD}} --mixed_precision bf16 \\',
            f'  "${{KOHYA_DIR}}/{train_script}" \\',
            f'  --config_file "{toml_path}"',
            f'echo "{name} training complete."',
            'echo ""',
            "",
        ])

    lines.extend([
        'echo "All LoRA training complete!"',
        f'echo "Models saved to: {LORA_MODELS_DIR}"',
    ])

    script_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    script_path.chmod(0o755)
    return script_path


