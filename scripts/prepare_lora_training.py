def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Prepare LoRA training datasets for AI Influencer characters",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s --character aria_nova
  %(prog)s --all
  %(prog)s --character aria_nova --master-dir /path/to/masters
  %(prog)s --all --output-dir /custom/output
        """,
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--character",
        type=str,
        help="Character slug to prepare",
    )
    group.add_argument(
        "--all",
        action="store_true",
        help="Prepare datasets for all characters",
    )
    parser.add_argument(
        "--master-dir",
        type=Path,
        default=None,
        help="Override master images directory (for single character mode)",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Override output dataset directory",
    )
    parser.add_argument(
        "--personas",
        type=Path,
        default=PERSONAS_PATH,
        help=f"Path to personas.json (default: {PERSONAS_PATH})",
    )
    parser.add_argument(
        "--lora-config",
        type=Path,
        default=LORA_CONFIG_PATH,
        help=f"Path to lora_training_config.json (default: {LORA_CONFIG_PATH})",
    )
    parser.add_argument(
        "--reg-dir",
        type=Path,
        default=REG_IMAGES_DIR,
        help=f"Path to regularisation images (default: {REG_IMAGES_DIR})",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable debug logging",
    )
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    # Load configs
    logger.info("Loading personas from %s", args.personas)
    personas = load_personas(args.personas)

    logger.info("Loading LoRA config from %s", args.lora_config)
    lora_config = load_lora_config(args.lora_config)

    if args.all:
        # Batch mode: prepare all characters
        output_dir = args.output_dir or LORA_DATASETS_DIR
        prepare_all_characters(
            personas=personas,
            lora_config=lora_config,
            master_base_dir=MASTER_IMAGES_DIR,
            output_base_dir=output_dir,
            reg_dir=args.reg_dir,
        )
    else:
        # Single character mode
        slug = args.character
        character = get_character(personas, slug)
        master_dir = args.master_dir or (MASTER_IMAGES_DIR / slug)
        output_dir = args.output_dir or (LORA_DATASETS_DIR / slug)

        toml_path = prepare_dataset_for_character(
            character=character,
            lora_config=lora_config,
            master_dir=master_dir,
            output_dir=output_dir,
            reg_dir=args.reg_dir,
        )

        model_type = lora_config.get("model", {}).get("model_type", "flux")
        train_script = "flux_train_network.py" if model_type == "flux" else "sdxl_train_network.py"
        logger.info("")
        logger.info("Done! To start training:")
        logger.info(
            "  accelerate launch --mixed_precision bf16 "
            "/path/to/kohya_ss/sd-scripts/%s "
            "--config_file %s",
            train_script,
            toml_path,
        )


if __name__ == "__main__":
    main()
